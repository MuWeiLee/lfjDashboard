# setup-wind-env.ps1 - read ~/.wind-aifinmarket/config, generate project .env (no key printed)
#
# Usage (run by user, ExecutionPolicy Bypass required on this machine):
#   powershell -ExecutionPolicy Bypass -File scripts\setup-wind-env.ps1
#
# Mapping (same failover order as wind-client.js):
#   WIND_API_KEY_LFJ = config WIND_API_KEY_YYH
#   WIND_API_KEY_HF  = config WIND_API_KEY_HF
#   WIND_API_KEY_ZZY = config WIND_API_KEY_ZZY
$ErrorActionPreference = "Stop"

$cfgPath = Join-Path $HOME ".wind-aifinmarket\config"
if (-not (Test-Path $cfgPath)) { Write-Output "config not found: $cfgPath"; exit 1 }

$kv = @{}
Get-Content $cfgPath -ErrorAction Stop | ForEach-Object {
  $line = $_.Trim()
  if ($line -and -not $line.StartsWith("#")) {
    $parts = $line.Split("=", 2)
    if ($parts.Count -eq 2 -and $parts[0].Trim() -and $parts[1].Trim()) { $kv[$parts[0].Trim()] = $parts[1].Trim() }
  }
}

$lfj = $kv["WIND_API_KEY_YYH"]; $hf = $kv["WIND_API_KEY_HF"]; $zzy = $kv["WIND_API_KEY_ZZY"]
if (-not $lfj) { Write-Output "WIND_API_KEY_YYH missing in config"; exit 1 }

$envPath = Join-Path (Split-Path $PSScriptRoot -Parent) ".env"
$content = @(
  "# Generated by scripts/setup-wind-env.ps1 from $cfgPath",
  "# LFJ slot = YYH key (failover order: LFJ -> HF -> ZZY)",
  "WIND_API_KEY_LFJ=$lfj",
  "WIND_API_KEY_HF=$hf",
  "WIND_API_KEY_ZZY=$zzy",
  ""
) -join "`r`n"
[System.IO.File]::WriteAllText($envPath, $content, (New-Object System.Text.UTF8Encoding($false)))
Write-Output ("written: " + $envPath + " (LFJ=" + $lfj.Length + " HF=" + $hf.Length + " ZZY=" + $zzy.Length + " chars)")